// Kotlin side of the Rust bridge. The generated UniFFI bindings and the
// UniffiCoreClient adapter are compiled only when -Psonora.rust=true; until then
// the app runs on DemoCoreClient. See docs/BRIDGE.md.
plugins {
    alias(libs.plugins.android.library)
    alias(libs.plugins.kotlin.android)
}

android {
    namespace = "dev.sonora.core"
    compileSdk = 35

    defaultConfig {
        minSdk = 26
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions {
        jvmTarget = "17"
    }

    // Bindings generated by scripts/gen-bindings.sh, plus the .so files produced
    // by scripts/build-rust.sh (jniLibs/<abi>/libsonora_core.so).
    sourceSets["main"].java.srcDir("src/generated/kotlin")
    sourceSets["main"].jniLibs.srcDir("src/main/jniLibs")
    if (providers.gradleProperty("sonora.rust").orNull == "true") {
        sourceSets["main"].kotlin.srcDir("src/rust/kotlin")
    }
}

dependencies {
    api(libs.kotlinx.coroutines.core)
    api(libs.kotlinx.coroutines.android)

    testImplementation(libs.junit)
    testImplementation(libs.turbine)
    testImplementation(libs.kotlinx.coroutines.test)
}
