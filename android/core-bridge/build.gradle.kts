// Kotlin side of the Rust bridge. The generated UniFFI bindings and the
// UniffiCoreClient adapter are compiled only when -Psonora.rust=true; until then
// the app runs on DemoCoreClient. See docs/BRIDGE.md.
plugins {
    alias(libs.plugins.android.library)
    alias(libs.plugins.kotlin.android)
}

val rustBinding: Boolean = providers.gradleProperty("sonora.rust").orNull == "true"

android {
    namespace = "dev.sonora.core"
    compileSdk = 35

    defaultConfig {
        minSdk = 26
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
        // UniFFI's generated object Cleaner uses java.lang.ref.Cleaner, which is
        // API 33+. Desugaring is only needed when the generated bindings are
        // compiled in (minSdk is 26), so the demo build keeps its old behaviour.
        isCoreLibraryDesugaringEnabled = rustBinding
    }
    kotlinOptions {
        jvmTarget = "17"
    }

    // Bindings generated by scripts/gen-bindings.sh and by the `Android native` CI
    // job (`--out-dir android/core-bridge/src/generated`), plus the .so files
    // produced by scripts/build-rust.sh (jniLibs/<abi>/libsonora_core.so).
    // The generated package path is <out-dir>/dev/sonora/core/ffi, so the source
    // root must be the out-dir itself, not a "kotlin" subdirectory.
    //
    // Both roots are conditional: generated bindings reference JNA, which is only
    // on the classpath for `-Psonora.rust=true`, so compiling them into a default
    // build would fail to resolve it. jniLibs is gated for the same reason — a
    // stale .so should never be packaged into the demo APK.
    if (rustBinding) {
        sourceSets["main"].java.srcDir("src/generated")
        sourceSets["main"].kotlin.srcDir("src/rust/kotlin")
        sourceSets["main"].jniLibs.srcDir("src/main/jniLibs")
    }
}

dependencies {
    api(libs.kotlinx.coroutines.core)
    api(libs.kotlinx.coroutines.android)

    // Only the native build carries generated UniFFI Kotlin. JNA carries *every*
    // native call the generated bindings make, not just the object cleaner, and it
    // must be the `@aar` artifact: the plain jar contains only Java classes, while
    // the aar also ships libjnidispatch.so per ABI. With the jar, JNA fails to find
    // its native dispatcher on a device and every call into the core throws (the
    // app then falls back with NATIVE_LOAD_FAILED). desugar_jdk_libs provides
    // java.lang.ref.Cleaner on API 26+.
    if (rustBinding) {
        implementation("net.java.dev.jna:jna:${libs.versions.jna.get()}@aar")
        coreLibraryDesugaring(libs.desugar.jdk.libs)
    }

    testImplementation(libs.junit)
    testImplementation(libs.turbine)
    testImplementation(libs.kotlinx.coroutines.test)
}
